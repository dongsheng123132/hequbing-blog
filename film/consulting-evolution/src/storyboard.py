    events: dict = field(default_factory=dict)   # 名称 -> 章内拍

    @property
    def f0(self):
        return T.beat_frame(self.chapter, self.b0)

    @property
    def f1(self):
        return T.beat_frame(self.chapter, self.b1)

    @property
    def beats(self):
        return self.b1 - self.b0


