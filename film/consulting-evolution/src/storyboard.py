@dataclass
class Shot:
    id: str
    chapter: int
    b0: int
    b1: int
    keyword: str            # 大号书法关键词（章主字）
    phrase: str             # 镜头短语（辅助关键词）
    subject: str            # 主体草图
    action: str             # 动作 / 状态变化
    transition: str         # 转出方式
