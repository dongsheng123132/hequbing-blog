def by_id():
    return {s.id: s for s in SHOTS}


def shot_at(frame):
    for s in SHOTS:
        if s.f0 <= frame < s.f1:
            return s
    if frame == T.TOTAL_FRAMES:
        return SHOTS[-1]
    raise ValueError(frame)


def event_frame(shot, name):
    return T.beat_frame(shot.chapter, shot.events[name]) if float(shot.events[name]).is_integer() \
        else T.chapter_start_frame(shot.chapter) + round(shot.events[name] * T.CHAPTERS[shot.chapter].frames_per_beat)


def validate_structure():
    """镜头必须首尾相接、落在整拍、覆盖全片；章切换落在小节首拍。"""
    errs = []
    prev_end = 0
    for s in SHOTS:
        if s.f0 != prev_end:
            errs.append(f"{s.id} 起点 {s.f0} 与上一镜头终点 {prev_end} 不接")
        if s.keyword != T.CHAPTERS[s.chapter].key:
            errs.append(f"{s.id} 关键词不是本章主字")
        if s.b1 > T.CHAPTERS[s.chapter].beats:
            errs.append(f"{s.id} 超出本章")
        prev_end = s.f1
    if prev_end != T.TOTAL_FRAMES:
        errs.append(f"镜头总长 {prev_end} ≠ {T.TOTAL_FRAMES}")
    for ch in T.CHAPTERS:
        firsts = [s for s in SHOTS if s.chapter == ch.id]
        if firsts[0].b0 != 0:
            errs.append(f"第 {ch.id} 章首镜头不在第 0 拍")
    return errs


def narration_for(shot):
    ids = []
    for ln in LINES:
        if ln.chapter == shot.chapter and shot.b0 <= ln.beat < shot.b1:
            ids.append(ln.id)
    return ids


def write_storyboard_csv(path):
    nar = {l.id: l for l in LINES}
    rows = []
    for s in SHOTS:
        ids = narration_for(s)
        rows.append({
            "镜头ID": s.id, "章节ID": s.chapter, "章节": T.CHAPTERS[s.chapter].name,
            "起始拍": s.b0, "结束拍": s.b1, "拍数": s.beats,
            "起始帧": s.f0, "结束帧(排他)": s.f1,
            "起始时间码": T.timecode(s.f0), "结束时间码": T.timecode(s.f1),
            "关键词": s.keyword, "镜头短语": s.phrase, "主体草图": s.subject, "动作": s.action,
            "旁白": " ".join(nar[i].display for i in ids), "旁白ID": ";".join(ids),
            "关键动作拍": ";".join(f"{k}@{v}" for k, v in s.events.items()),
            "声音": s.sound, "转场": s.transition, "历史来源ID": s.sources,
        })
    with open(path, "w", newline="", encoding="utf-8-sig") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    return rows


